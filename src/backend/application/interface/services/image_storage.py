"""Порт хранилища загружаемых изображений.

presentation не должен знать, куда именно кладут файл: на диск, в S3 или в
другое хранилище. Поэтому контракт и тип ошибки живут в application, а
реализация подключается через DI.
"""

from __future__ import annotations

from abc import ABC, abstractmethod


class ImageStorageError(ValueError):
    """Файл нельзя принять или сохранить как изображение.

    Наследуется от ``ValueError``, потому что для вызывающего кода это ошибка
    входных данных запроса: ответ всегда 4xx с текстом причины, а не сбой
    инфраструктуры.
    """


class ImageStoragePort(ABC):
    """Хранилище картинок, загружаемых пользователями."""

    @abstractmethod
    async def save(self, upload, subdir: str) -> str:
        """Сохранить загруженное изображение и вернуть его публичный URL.

        Args:
            upload: ``UploadFile`` из multipart-формы.
            subdir: Подкаталог хранилища, безопасное slug-имя без путей.

        Returns:
            str: Публичный URL сохранённого файла.

        Raises:
            ImageStorageError: Файл отсутствует, каталог недопустим, формат не
                распознан по содержимому либо размер превышает лимит.
        """
